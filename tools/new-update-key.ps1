# Creates the RSA key that signs Snapline updates. Run once.
#  - The PRIVATE key is saved to %APPDATA%\Coursion\keys\snapline-update.xml, outside the repo.
#    Back it up (e.g. in 1Password). Without it you can't ship updates to existing installs.
#  - The PUBLIC key is written into src\UpdateKey.cs, which Snapline uses to check every update.
$ErrorActionPreference = 'Stop'
$keyDir = Join-Path $env:APPDATA 'Coursion\keys'
$keyFile = Join-Path $keyDir 'snapline-update.xml'
if (Test-Path $keyFile) { throw "A key already exists at $keyFile. Refusing to overwrite it." }
New-Item -ItemType Directory -Force $keyDir | Out-Null

$rsa = New-Object System.Security.Cryptography.RSACryptoServiceProvider -ArgumentList 3072, (New-Object System.Security.Cryptography.CspParameters 24)
$rsa.PersistKeyInCsp = $false
Set-Content -Path $keyFile -Value $rsa.ToXmlString($true) -Encoding ascii -NoNewline
$public = $rsa.ToXmlString($false)

$cs = @"
// Public half of the Snapline update signing key (generated by tools\new-update-key.ps1).
// Every downloaded update must be signed with the matching private key, or it is refused.
namespace Snapline.Updates;

static class UpdateKey
{
    public const string PublicXml = "$public";
}
"@
Set-Content -Path (Join-Path $PSScriptRoot '..\Snapline\Updates\UpdateKey.cs') -Value $cs -Encoding utf8
Write-Host "Private key: $keyFile  (back this up, keep it secret)"
Write-Host "Public key written to Snapline\Updates\UpdateKey.cs"
